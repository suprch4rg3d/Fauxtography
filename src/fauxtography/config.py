"""Typed experiment configuration loaded from YAML files.

Simple and framework-free: each experiment (baseline / clip / dinov2) has its
own config under ``configs/``. Scripts call ``load_config("baseline", path)``
and get a fully-populated typed object.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, get_type_hints

import yaml


# --------------------------------------------------------------------------- #
# Shared pieces
# --------------------------------------------------------------------------- #
@dataclass
class DataConfig:
    root: str = "data"  # top-level data dir with train/val/test subfolders
    image_size: int = 224
    num_workers: int = 4
    seed: int = 42


@dataclass
class OutputConfig:
    run_dir: str = "experiments/runs"  # checkpoints / extracted features
    results_dir: str = "results"  # committed metrics + figures


# --------------------------------------------------------------------------- #
# Baseline (ResNet fine-tune)
# --------------------------------------------------------------------------- #
@dataclass
class BaselineConfig:
    name: str = "baseline"
    arch: str = "resnet18"  # resnet18 / resnet50
    pretrained: bool = True
    freeze_backbone: bool = False
    epochs: int = 12
    batch_size: int = 64
    lr: float = 1e-3
    weight_decay: float = 0.0
    data: DataConfig = field(default_factory=DataConfig)
    output: OutputConfig = field(default_factory=OutputConfig)


# --------------------------------------------------------------------------- #
# CLIP (zero-shot)
# --------------------------------------------------------------------------- #
@dataclass
class ClipConfig:
    name: str = "clip"
    model_name: str = "openai/clip-vit-base-patch32"
    batch_size: int = 64
    num_workers: int = 4
    prompts_real: list[str] = field(
        default_factory=lambda: ["a real photograph taken with a camera", "a genuine photo of a real scene"]
    )
    prompts_fake: list[str] = field(
        default_factory=lambda: ["an image generated by artificial intelligence", "a fake AI-generated image"]
    )
    data: DataConfig = field(default_factory=DataConfig)
    output: OutputConfig = field(default_factory=OutputConfig)


# --------------------------------------------------------------------------- #
# DINOv2 (feature extraction + linear probe)
# --------------------------------------------------------------------------- #
@dataclass
class Dinov2Config:
    name: str = "dinov2"
    arch: str = "dinov2_vitb14"  # vits14 / vitb14 / vitl14
    feature_batch_size: int = 64
    probe_batch_size: int = 128
    probe_epochs: int = 20
    probe_lr: float = 1e-2
    probe_weight_decay: float = 0.0
    num_workers: int = 4
    data: DataConfig = field(default_factory=DataConfig)
    output: OutputConfig = field(default_factory=OutputConfig)


# --------------------------------------------------------------------------- #
# Loading
# --------------------------------------------------------------------------- #
_CONFIG_TYPES: dict[str, type] = {
    "baseline": BaselineConfig,
    "clip": ClipConfig,
    "dinov2": Dinov2Config,
}


def load_config(name: str, path: str | Path | None = None) -> Any:
    """Load a config ``name`` from a YAML ``path`` (default: configs/<name>.yaml)."""
    if name not in _CONFIG_TYPES:
        raise ValueError(f"Unknown config name {name!r}; expected one of {list(_CONFIG_TYPES)}")
    cfg_type = _CONFIG_TYPES[name]

    if path is None:
        path = Path(__file__).resolve().parents[2] / "configs" / f"{name}.yaml"
    path = Path(path)

    raw: dict[str, Any] = {}
    if path.exists():
        with open(path) as fh:
            raw = yaml.safe_load(fh) or {}

    return _build(cfg_type, raw)


def _build(cfg_type: type, raw: dict[str, Any]) -> Any:
    """Construct a (possibly nested) dataclass from a YAML dict."""
    raw = raw or {}
    if not hasattr(cfg_type, "__dataclass_fields__"):
        return raw

    hints = get_type_hints(cfg_type)
    kwargs: dict[str, Any] = {}
    for fname, f in cfg_type.__dataclass_fields__.items():
        if fname not in raw:
            continue
        val = raw[fname]
        ftype = hints.get(fname, f.type)
        if hasattr(ftype, "__dataclass_fields__"):
            kwargs[fname] = _build(ftype, val)
        else:
            kwargs[fname] = val
    return cfg_type(**kwargs)


# --------------------------------------------------------------------------- #
# Misc helpers
# --------------------------------------------------------------------------- #
def config_to_dict(cfg: Any) -> dict[str, Any]:
    """Convert a config object to a plain dict for reporting/JSON."""
    return asdict(cfg)